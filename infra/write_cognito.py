    f.write('  callback_urls = [\n')
    f.write('    "https://app.scoutcloud.dev",\n')
    f.write('    "http://localhost:8080",\n')
    f.write('  ]\n\n')
    f.write('  logout_urls = [\n')
    f.write('    "https://app.scoutcloud.dev",\n')
    f.write('    "http://localhost:8080",\n')
    f.write('  ]\n\n')
    f.write('  supported_identity_providers = ["COGNITO"]\n\n')
    f.write('  explicit_auth_flows = [\n')
    f.write('    "ALLOW_REFRESH_TOKEN_AUTH",\n')
    f.write('    "ALLOW_USER_PASSWORD_AUTH",\n')
    f.write('    "ALLOW_USER_SRP_AUTH",\n')
    f.write('  ]\n\n')
    f.write('  access_token_validity  = 1\n')
    f.write('  id_token_validity      = 1\n')
    f.write('  refresh_token_validity = 30\n\n')
