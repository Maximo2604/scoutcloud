    f.write('  tags = { Project = "scoutcloud" }\n')
    f.write('}\n\n')
    f.write('resource "aws_cognito_user_pool_client" "web" {\n')
    f.write('  name         = "scoutcloud-web"\n')
    f.write('  user_pool_id = aws_cognito_user_pool.main.id\n\n')
    f.write('  generate_secret                      = false\n')
    f.write('  allowed_oauth_flows                  = ["code"]\n')
    f.write('  allowed_oauth_flows_user_pool_client = true\n')
