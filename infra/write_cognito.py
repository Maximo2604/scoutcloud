    f.write('    access_token  = "hours"\n')
    f.write('    id_token      = "hours"\n')
    f.write('    refresh_token = "days"\n')
    f.write('  }\n')
    f.write('}\n\n')
    f.write('resource "aws_cognito_user_pool_domain" "main" {\n')
    f.write('  domain       = "scoutcloud-auth"\n')
    f.write('  user_pool_id = aws_cognito_user_pool.main.id\n')
    f.write('}\n\n')
    f.write('resource "aws_apigatewayv2_api" "main" {\n')
    f.write('  name          = "scoutcloud-api"\n')
    f.write('  protocol_type = "HTTP"\n')
    f.write('  tags          = { Project = "scoutcloud" }\n')
    f.write('}\n\n')
    f.write('resource "aws_apigatewayv2_authorizer" "cognito" {\n')
    f.write('  api_id           = aws_apigatewayv2_api.main.id\n')
    f.write('  authorizer_type  = "JWT"\n')
    f.write('  name             = "cognito-authorizer"\n')
    f.write('  identity_sources = ["$request.header.Authorization"]\n\n')
    f.write('  jwt_configuration {\n')
    f.write('    audience = [aws_cognito_user_pool_client.web.id]\n')
    f.write('    issuer   = "https://cognito-idp.us-east-1.amazonaws.com/${aws_cognito_user_pool.main.id}"\n')
    f.write('  }\n')
    f.write('}\n\n')
    f.write('output "cognito_user_pool_id"     { value = aws_cognito_user_pool.main.id }\n')
    f.write('output "cognito_client_id"        { value = aws_cognito_user_pool_client.web.id }\n')
    f.write('output "cognito_hosted_ui_domain" { value = aws_cognito_user_pool_domain.main.domain }\n')
