    f.write('  auto_verified_attributes = ["email"]\n\n')
    f.write('  verification_message_template {\n')
    f.write('    default_email_option = "CONFIRM_WITH_CODE"\n')
    f.write('    email_subject        = "ScoutCloud - Verify your email"\n')
